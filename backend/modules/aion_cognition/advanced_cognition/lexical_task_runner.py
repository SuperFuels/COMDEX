#!/usr/bin/env python3
"""
🧠 AION Advanced Cognition - Task Runner
────────────────────────────────────────
Executes cognitive tasks generated by lexical_task_generator.
Evaluates semantic accuracy + resonance coherence.
"""

import json, time, logging
from pathlib import Path
import hashlib
from backend.modules.aion_cognition.native_lexical_intelligence import NativeLexicalIntelligence

log = logging.getLogger(__name__)

TASK_DIR = Path("data/tasks/advanced_cognition")

# ------------------------------------------------------------
def run_taskset(task_file: Path):
    """Compatibility entry point backed by the governed native examiner."""
    data = json.loads(task_file.read_text())
    requested = max(4, min(150, len(data.get("tasks") or [])))
    digest = hashlib.sha256(task_file.read_bytes()).hexdigest()
    repo_root = Path(__file__).resolve().parents[4]
    outcome = NativeLexicalIntelligence(repo_root=repo_root).run_practice_cycle(
        family="mixed", limit=requested, seed=int(digest[:8], 16),
        offset=int(digest[8:14], 16) % 100000,
        project_family=f"legacy_advanced_cognition_{digest[:12]}",
    )
    summary = {
        "avg_accuracy": outcome["score"],
        "avg_SQI": outcome["score"],
        "avg_stability": 1.0 if outcome["authority"].get("allow_learn") else 0.0,
        "count": outcome["total"],
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "model_used": False,
        "expected_withheld": outcome["expected_withheld"],
        "authority": outcome["authority"],
    }
    log.info("[LCE] Completed %s native tasks - acc=%s", outcome["total"], outcome["score"])
    return summary
